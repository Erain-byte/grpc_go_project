package repository

import (
	"context"
	"errors"
	"fmt"
	"strings"

	"user/internal/model"
	"user/internal/sharding"

	"gorm.io/gorm"
)

type UserRepository struct {
	db     *gorm.DB
	router *sharding.UserRouter
}

func NewUserRepository(db *gorm.DB, router *sharding.UserRouter) *UserRepository {
	return &UserRepository{db: db, router: router}
}

func (r *UserRepository) FindBySubject(ctx context.Context, subject string) (*model.User, error) {
	var identity model.UserIdentityIndex
	if err := r.db.WithContext(ctx).Where("keycloak_subject = ?", subject).First(&identity).Error; err != nil {
		return nil, err
	}
	tableName, err := r.router.TableNameByIndex(int(identity.TableIndex))
	if err != nil {
		return nil, err
	}
	var user model.User
	if err := r.db.WithContext(ctx).Table(tableName).Where("id = ?", identity.UserID).First(&user).Error; err != nil {
		return nil, err
	}
	return &user, nil
}

// FindByID resolves the global index first, then reads the user from its shard.
// Callers must not derive the shard from an untrusted request themselves.
func (r *UserRepository) FindByID(ctx context.Context, userID int64) (*model.User, error) {
	var identity model.UserIdentityIndex
	if err := r.db.WithContext(ctx).Where("user_id = ?", userID).First(&identity).Error; err != nil {
		return nil, err
	}
	tableName, err := r.router.TableNameByIndex(int(identity.TableIndex))
	if err != nil {
		return nil, err
	}
	var user model.User
	if err := r.db.WithContext(ctx).Table(tableName).Where("id = ?", identity.UserID).First(&user).Error; err != nil {
		return nil, err
	}
	return &user, nil
}

// List returns a globally ordered page across all user shards. The table names
// are generated by UserRouter rather than supplied by a request, so embedding
// them in this SQL is safe.
func (r *UserRepository) List(ctx context.Context, offset, limit int) ([]*model.User, int64, error) {
	if offset < 0 || limit <= 0 {
		return nil, 0, fmt.Errorf("invalid pagination offset=%d limit=%d", offset, limit)
	}
	tables := r.router.TableNames()
	if len(tables) == 0 {
		return nil, 0, fmt.Errorf("no user shard tables configured")
	}

	selects := make([]string, 0, len(tables))
	counts := make([]string, 0, len(tables))
	for _, table := range tables {
		selects = append(selects, "SELECT * FROM "+table)
		counts = append(counts, "SELECT COUNT(*) AS total FROM "+table)
	}

	var total int64
	countSQL := "SELECT COALESCE(SUM(total), 0) FROM (" + strings.Join(counts, " UNION ALL ") + ") AS shard_counts"
	if err := r.db.WithContext(ctx).Raw(countSQL).Scan(&total).Error; err != nil {
		return nil, 0, err
	}

	var users []*model.User
	listSQL := "SELECT * FROM (" + strings.Join(selects, " UNION ALL ") + ") AS shard_users " +
		"ORDER BY created_at DESC, id DESC LIMIT ? OFFSET ?"
	if err := r.db.WithContext(ctx).Raw(listSQL, limit, offset).Scan(&users).Error; err != nil {
		return nil, 0, err
	}
	return users, total, nil
}

func (r *UserRepository) FindOrCreateBySubject(ctx context.Context, user *model.User) (*model.User, bool, error) {
	existing, err := r.FindBySubject(ctx, user.KeycloakSubject)
	if err == nil {
		return existing, false, nil
	}
	if !errors.Is(err, gorm.ErrRecordNotFound) {
		return nil, false, err
	}

	txErr := r.db.WithContext(ctx).Transaction(func(tx *gorm.DB) error {
		index, routeErr := r.router.TableIndex(user.ID)
		if routeErr != nil {
			return routeErr
		}
		table, routeErr := r.router.TableNameByIndex(index)
		if routeErr != nil {
			return routeErr
		}
		if createErr := tx.Table(table).Create(user).Error; createErr != nil {
			return createErr
		}
		return tx.Create(&model.UserIdentityIndex{KeycloakSubject: user.KeycloakSubject, UserID: user.ID, TableIndex: int16(index)}).Error
	})
	if txErr == nil {
		return user, true, nil
	}

	// Concurrent initialization can lose the unique-key race. Return the winner.
	existing, lookupErr := r.FindBySubject(ctx, user.KeycloakSubject)
	if lookupErr == nil {
		return existing, false, nil
	}
	return nil, false, txErr
}
